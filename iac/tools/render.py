#!/usr/bin/env python3
"""Lab compiler around AVD.  Two phases, both deterministic and committed:

  render.py pre    iac/intent/hosts.yml  -> iac/build/connected_endpoints.yml   (AVD input)
  [AVD build]      iac/intent (inventory + group_vars) -> iac/build/intended/{structured_configs,configs}
  render.py post   AVD structured configs + intent/{wan,hosts}.yml ->
                     containerlab/netops.clab.yml          nodes + cabling (from AVD peer/peer_interface)
                     containerlab/init-configs/*.cfg       minimal cEOS bootstrap (mgmt, eAPI, gNMI)
                     containerlab/telemetry/gnmic/*.yml    gNMI targets + used-port filter
                     iac/build/lab-inventory.yml           FRR WAN + workload hosts for Ansible
"""
import ipaddress
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
INTENT, BUILD, CLAB = ROOT / "iac" / "intent", ROOT / "iac" / "build", ROOT / "containerlab"
STRUCTURED = BUILD / "intended" / "structured_configs"
LAB = "netops"
CEOS_IMAGE = "ceos:4.36.2F"
HOST_IMAGE = "ghcr.io/srl-labs/network-multitool:latest"
MGMT_GW = "172.20.20.1"
HEADER = "# GENERATED by iac/tools/render.py — do not edit\n"


def load(path: pathlib.Path):
    return yaml.safe_load(path.read_text())


def dump(path: pathlib.Path, data, header: str = HEADER) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(data, sort_keys=False, width=1000))


def clab_port(itf: str) -> str:
    """EOS Ethernet3 -> eth3 (cEOS maps ethN to EthernetN); linux ports pass through."""
    m = re.fullmatch(r"Ethernet(\d+)", itf)
    return f"eth{m.group(1)}" if m else itf


# `group` drives containerlab's built-in graph view (level + icon, NeXt UI sort order:
# superspine, dc-gw, spine, leaf, server, ...).
CLAB_GROUP = {"wan": "superspine", "bgw": "dc-gw", "spine": "spine", "leaf": "leaf", "host": "server", "telemetry": "1"}


# --------------------------------------------------------------------------- pre
def pre() -> None:
    hosts = load(INTENT / "hosts.yml")["hosts"]
    servers = [{
        "name": name,
        "adapters": [{"endpoint_ports": ["eth1"], "switch_ports": [h["port"]], "switches": [h["switch"]],
                      "vlans": str(h["vlan"]), "mode": "access", "spanning_tree_portfast": "edge"}],
    } for name, h in hosts.items()]
    dump(BUILD / "connected_endpoints.yml", {"servers": servers})
    if not (BUILD / "lab-inventory.yml").exists():          # first build: keep ansible's inventory parse quiet
        dump(BUILD / "lab-inventory.yml", {"all": {"children": {"WAN": {}, "SERVERS": {}}}})
    print(f"pre: {len(servers)} connected endpoints")


# --------------------------------------------------------------------------- post
def post() -> None:
    sc = {p.stem: load(p) for p in sorted(STRUCTURED.glob("*.yml"))}
    if not sc:
        sys.exit("no AVD structured configs — run the AVD build first")
    wan = load(INTENT / "wan.yml")
    hosts = load(INTENT / "hosts.yml")["hosts"]
    fabric_vars = load(INTENT / "group_vars" / "FABRIC" / "management.yml")
    admin_hash = next(u["sha512_password"] for u in fabric_vars["aaa_settings"]["local_users"] if u["name"] == "admin")

    links, wan_nodes, used_ports = set(), {}, {}
    for name, w in wan["routers"].items():
        wan_nodes[name] = {"name": name, "asn": w["asn"], "loopback": w["loopback"], "p2p": [], "src": "wan.yml"}

    for dev, cfg in sc.items():
        used_ports[dev] = sorted({e["name"] for e in cfg.get("ethernet_interfaces", [])}
                                 | {l["name"] for l in cfg.get("loopback_interfaces", [])}
                                 | ({"Vxlan1"} if cfg.get("vxlan_interface") else set()))
        for e in cfg.get("ethernet_interfaces", []):
            meta = e.get("metadata", {})
            peer, peer_itf = meta.get("peer", e.get("peer")), meta.get("peer_interface", e.get("peer_interface"))
            if not peer or not peer_itf:
                continue
            a, b = (dev, clab_port(e["name"])), (peer, clab_port(peer_itf))
            links.add(tuple(sorted([a, b])))
            if peer in wan_nodes:                       # FRR side of an l3_edge link, derived from AVD
                local = ipaddress.ip_interface(e["ip_address"])
                far = next(ip for ip in local.network if ip != local.ip)          # other end of the /31
                wan_nodes[peer]["p2p"].append({
                    "name": peer_itf, "ip": f"{far}/{local.network.prefixlen}", "peer": dev,
                    "peer_port": e["name"], "peer_ip": str(local.ip), "peer_asn": int(cfg["router_bgp"]["as"])})

    for l in wan.get("links", []):                      # WAN-internal links
        (an, ap), (bn, bp) = l["a"].split(":"), l["b"].split(":")
        net = ipaddress.ip_network(l["subnet"])
        for (n, p, ip), (pn, pp, pip) in [((an, ap, net[0]), (bn, bp, net[1])), ((bn, bp, net[1]), (an, ap, net[0]))]:
            wan_nodes[n]["p2p"].append({"name": p, "ip": f"{ip}/{net.prefixlen}", "peer": pn, "peer_port": pp,
                                        "peer_ip": str(pip), "peer_asn": wan["routers"][pn]["asn"]})
        links.add(tuple(sorted([(an, ap), (bn, bp)])))
    for w in wan_nodes.values():
        w["p2p"].sort(key=lambda p: (len(p["name"]), p["name"]))

    servers = {}
    for name, h in hosts.items():
        svi = next(v for v in sc[h["switch"]].get("vlan_interfaces", []) if v["name"] == f"Vlan{h['vlan']}")
        servers[name] = {"ip": h["ip"], "gw": str(ipaddress.ip_interface(svi["ip_address_virtual"]).ip),
                         "switch": h["switch"], "switch_port": h["port"], "vlan": h["vlan"]}

    # ---- containerlab topology
    nodes = {}
    for dev, cfg in sc.items():
        mgmt = ipaddress.ip_interface(cfg["management_interfaces"][0]["ip_address"])
        meta = cfg.get("metadata", {})
        nodes[dev] = {"kind": "arista_ceos", "mgmt-ipv4": str(mgmt.ip),
                      "startup-config": f"init-configs/{dev}.cfg",
                      "labels": {"site": meta.get("dc_name", "").lower(),
                                 "role": next((r for r in ("spine", "bgw", "leaf") if r in dev), "switch")}}
        (CLAB / "init-configs").mkdir(parents=True, exist_ok=True)
        (CLAB / "init-configs" / f"{dev}.cfg").write_text(BOOTSTRAP.format(
            name=dev, mgmt=mgmt.with_prefixlen, gw=MGMT_GW, admin_hash=admin_hash))
    for name, w in wan["routers"].items():
        nodes[name] = {"kind": "linux", "image": wan["image"], "mgmt-ipv4": w["mgmt_ip"],
                       "labels": {"site": "wan", "role": "wan"},
                       "binds": ["static/frr/daemons:/etc/frr/daemons:ro", "static/frr/vtysh.conf:/etc/frr/vtysh.conf:ro"]}
    for name, s in servers.items():
        nodes[name] = {"kind": "linux", "image": HOST_IMAGE, "labels": {"site": name.split("-")[0], "role": "host"}}
    nodes["otelcol"] = {
        "kind": "linux", "image": "otel/opentelemetry-collector-contrib:0.162.0", "mgmt-ipv4": "172.20.20.250",
        "labels": {"role": "telemetry"}, "binds": ["telemetry/otelcol:/etc/otelcol:ro"],
        "env-files": ["telemetry/otelcol/elastic.env"],
        "cmd": "--config /etc/otelcol/base.yml --config /etc/otelcol/extra.yml", "ports": ["9464:9464"]}
    nodes["gnmic"] = {
        "kind": "linux", "image": "ghcr.io/openconfig/gnmic:0.49.0", "mgmt-ipv4": "172.20.20.251",
        "labels": {"role": "telemetry"}, "binds": ["telemetry/gnmic:/etc/gnmic:ro"],
        "env-files": ["telemetry/gnmic/gnmic.env"], "cmd": "--config /etc/gnmic/gnmic.yml subscribe"}
    for n in nodes.values():
        n["group"] = CLAB_GROUP[n["labels"]["role"]]
    topo = {"name": LAB,
            "mgmt": {"network": "clab-mgmt", "ipv4-subnet": "172.20.20.0/24"},
            "topology": {"kinds": {"arista_ceos": {
                             "image": CEOS_IMAGE, "enforce-startup-config": True,
                             # eth0 -> Management1, ethN -> EthernetN: same names as hardware / AVD cEOSLab profile
                             "binds": ["static/ceos/interface_mapping.json:/mnt/flash/EosIntfMapping.json:ro"]}},
                         "nodes": nodes,
                         "links": [{"endpoints": [f"{a}:{ap}", f"{b}:{bp}"]} for (a, ap), (b, bp) in sorted(links)]}}
    dump(CLAB / "netops.clab.yml", topo)

    # ---- telemetry
    targets = {f"{nodes[d]['mgmt-ipv4']}:6030": {
        "name": d, "insecure": True,
        "event-tags": {"site": nodes[d]["labels"]["site"], "role": nodes[d]["labels"]["role"], "vendor": "arista"}}
        for d in sc}
    dump(CLAB / "telemetry" / "gnmic" / "targets.yml", targets)
    gn = load(CLAB / "telemetry" / "gnmic" / "gnmic.base.yml")
    gn.setdefault("processors", {})["used-ports"] = {"event-drop": {"condition": (
        ".tags.interface_name != null and (.tags.interface_name as $i "
        f"| ({json.dumps(used_ports, separators=(',', ':'))}[.tags.source] // []) | index([$i]) == null)")}}
    gn["outputs"]["otel"]["event-processors"] = ["used-ports", *gn["outputs"]["otel"].get("event-processors", [])]
    dump(CLAB / "telemetry" / "gnmic" / "gnmic.yml", gn)

    # ---- Ansible inventory for the non-Arista parts
    inv = {"all": {"children": {
        "WAN": {"vars": {"ansible_connection": "community.docker.docker", "ansible_python_interpreter": "/usr/bin/python3"},
                "hosts": {n: {"ansible_host": f"clab-{LAB}-{n}", "node": w} for n, w in wan_nodes.items()}},
        "SERVERS": {"vars": {"ansible_connection": "community.docker.docker", "ansible_python_interpreter": "/usr/bin/python3"},
                    "hosts": {n: {"ansible_host": f"clab-{LAB}-{n}", "server": s} for n, s in servers.items()}},
    }}}
    dump(BUILD / "lab-inventory.yml", inv)
    print(f"post: {len(sc)} cEOS, {len(wan_nodes)} WAN, {len(servers)} hosts, {len(links)} links")


BOOTSTRAP = """! GENERATED by iac/tools/render.py — minimal day-0 bootstrap; AVD replaces the full config on apply
hostname {name}
!
no aaa root
username admin privilege 15 role network-admin secret sha512 {admin_hash}
!
vrf instance MGMT
!
platform tfa
   personality arfa
!
service routing protocols model multi-agent
!
management api http-commands
   protocol https
   no shutdown
   !
   vrf MGMT
      no shutdown
!
management api gnmi
   transport grpc default
      vrf MGMT
   provider eos-native
!
aaa authorization exec default local
!
interface Management1
   vrf MGMT
   ip address {mgmt}
!
ip route vrf MGMT 0.0.0.0/0 {gw}
!
end
"""

if __name__ == "__main__":
    {"pre": pre, "post": post}.get(sys.argv[1] if len(sys.argv) > 1 else "", lambda: sys.exit(__doc__))()
